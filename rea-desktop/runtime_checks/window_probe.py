"""Bounded native probe. Sends events only to a verified child-process window.

Screenshots are generated by the child's OpenGL diagnostics, never by reading
the desktop. All subprocesses launched here are terminated at the deadline.
"""
import argparse
import ctypes as C
import hashlib
import json
import os
from pathlib import Path
import re
import signal
import subprocess
import time


class KeyEvent(C.Structure):
    _fields_ = [
        ("type", C.c_int), ("serial", C.c_ulong), ("send_event", C.c_int),
        ("display", C.c_void_p), ("window", C.c_ulong), ("root", C.c_ulong),
        ("subwindow", C.c_ulong), ("time", C.c_ulong),
        ("x", C.c_int), ("y", C.c_int), ("x_root", C.c_int), ("y_root", C.c_int),
        ("state", C.c_uint), ("keycode", C.c_uint), ("same_screen", C.c_int),
    ]


class Event(C.Union):
    _fields_ = [("key", KeyEvent), ("pad", C.c_long * 24)]


class ChildWindow:
    def __init__(self, pid):
        self.pid = pid
        self.lib = C.CDLL("libX11.so.6")
        self.lib.XOpenDisplay.restype = C.c_void_p
        self.lib.XDefaultRootWindow.argtypes = [C.c_void_p]
        self.lib.XDefaultRootWindow.restype = C.c_ulong
        self.lib.XStringToKeysym.argtypes = [C.c_char_p]
        self.lib.XStringToKeysym.restype = C.c_ulong
        self.lib.XKeysymToKeycode.argtypes = [C.c_void_p, C.c_ulong]
        self.lib.XKeysymToKeycode.restype = C.c_uint
        self.lib.XSendEvent.argtypes = [C.c_void_p, C.c_ulong, C.c_int, C.c_long, C.POINTER(Event)]
        self.lib.XFlush.argtypes = [C.c_void_p]
        self.lib.XCloseDisplay.argtypes = [C.c_void_p]
        # The game may close between Escape-down and Escape-up. Keep Xlib's
        # default fatal error handler from bypassing the subprocess cleanup.
        handler_type = C.CFUNCTYPE(C.c_int, C.c_void_p, C.c_void_p)
        self.error_handler = handler_type(lambda display, event: 0)
        self.lib.XSetErrorHandler.argtypes = [handler_type]
        self.lib.XSetErrorHandler(self.error_handler)
        self.display = self.lib.XOpenDisplay(None)
        if not self.display:
            raise RuntimeError("Display unavailable")
        self.window = None

    def find(self):
        tree = subprocess.run(["xwininfo", "-root", "-tree"], capture_output=True, text=True, check=True).stdout
        for line in tree.splitlines():
            if "REA - recompiled PS2" not in line:
                continue
            ident = re.search(r"0x[0-9a-f]+", line)
            if not ident:
                continue
            wid = ident.group()
            prop = subprocess.run(["xprop", "-id", wid, "_NET_WM_PID"], capture_output=True, text=True).stdout
            if re.search(r"=\s*" + str(self.pid) + r"\s*$", prop):
                self.window = int(wid, 16)
                return self.window
        return None

    def event(self, kind, code, x=0, y=0):
        if not self.window and not self.find():
            raise RuntimeError("Child window not found")
        event = Event()
        event.key = KeyEvent(
            kind, 0, 1, self.display, self.window,
            self.lib.XDefaultRootWindow(self.display), 0, 0,
            x, y, x, y, 0, code, 1,
        )
        mask = {2: 1, 3: 2, 4: 4, 5: 8, 6: 64}[kind]
        self.lib.XSendEvent(self.display, self.window, 0, mask, C.byref(event))
        self.lib.XFlush(self.display)

    def key(self, name, hold):
        code = self.lib.XKeysymToKeycode(self.display, self.lib.XStringToKeysym(name.encode()))
        if not code:
            raise ValueError(name)
        self.event(2, code)
        time.sleep(hold)
        self.event(3, code)

    def click(self, x, y):
        self.event(6, 0, x, y)
        time.sleep(.15)
        self.event(4, 1, x, y)
        time.sleep(.15)
        self.event(5, 1, x, y)

    def close(self):
        self.lib.XCloseDisplay(self.display)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("executable", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--seconds", type=int, default=150)
    parser.add_argument("--ui", action="store_true")
    parser.add_argument("--events", type=Path, help="JSON list with at/key/hold or at/click")
    args = parser.parse_args()
    exe = args.executable.resolve()
    output = args.output.resolve()
    output.mkdir(exist_ok=False)
    events = json.loads(args.events.read_text()) if args.events else []
    env = dict(os.environ, REA_DIAGNOSTICS="1", REA_PAD_TRACE="1", REA_FRAME_DIR=str(output))
    if args.ui:
        env.pop("REA_SKIP_CONTROLS", None)
        env["REA_CONTROLS_FRAME"] = str(output / "controls.png")
    else:
        env["REA_SKIP_CONTROLS"] = "1"
    result = {"executable": str(exe), "sha256": hashlib.sha256(exe.read_bytes()).hexdigest(), "inputs": []}
    queue = output / "commands.jsonl"
    queue.write_text("")
    queued = 0
    started = time.monotonic()
    child = window = None
    try:
        with (output / "run.log").open("wb") as log:
            child = subprocess.Popen([str(exe)], cwd=exe.parent, env=env, stdout=log, stderr=log, start_new_session=True)
            window = ChildWindow(child.pid)
            while child.poll() is None and time.monotonic() - started < min(args.seconds, 600):
                elapsed = time.monotonic() - started
                lines = queue.read_text().splitlines()
                for line in lines[queued:]:
                    command = json.loads(line)
                    command["at"] = elapsed
                    events.append(command)
                queued = len(lines)
                events.sort(key=lambda event: event["at"])
                (output / "live.json").write_text(json.dumps({"pid": child.pid, "elapsed": elapsed}))
                if events and elapsed >= events[0]["at"] and window.find():
                    event = events.pop(0)
                    if "click" in event:
                        window.click(*event["click"])
                    else:
                        window.key(event["key"], min(4, max(.1, event.get("hold", .4))))
                    result["inputs"].append(dict(event, actual=elapsed))
                if log.tell() > 64 * 1024 * 1024:
                    raise RuntimeError("Diagnostic log limit exceeded")
                time.sleep(.2)
            result["elapsed"] = time.monotonic() - started
            result["exit_code"] = child.poll()
    finally:
        if child:
            try:
                os.killpg(child.pid, signal.SIGTERM)
                child.wait(timeout=4)
            except subprocess.TimeoutExpired:
                os.killpg(child.pid, signal.SIGKILL)
                child.wait()
            except ProcessLookupError:
                pass
        if window:
            window.close()
        (output / "result.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result))


if __name__ == "__main__":
    main()
